-- P0：登录账号和工厂模型。表名大写，方便以后在区分大小写的 MySQL 上使用。

CREATE TABLE IF NOT EXISTS SYS_USER (
  USER_ID VARCHAR(64) NOT NULL,
  LOGIN_NAME VARCHAR(64) NOT NULL,
  DISPLAY_NAME VARCHAR(128) NOT NULL,
  PASSWORD_HASH VARCHAR(256) NOT NULL,
  IS_ENABLED TINYINT NOT NULL DEFAULT 1,
  CREATE_ON DATETIME NOT NULL,
  PRIMARY KEY (USER_ID),
  UNIQUE KEY UK_SYS_USER_LOGIN (LOGIN_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS SYS_ROLE (
  ROLE_ID VARCHAR(64) NOT NULL,
  ROLE_CODE VARCHAR(64) NOT NULL,
  ROLE_NAME VARCHAR(128) NOT NULL,
  PRIMARY KEY (ROLE_ID),
  UNIQUE KEY UK_SYS_ROLE_CODE (ROLE_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS SYS_USER_ROLE (
  USER_ID VARCHAR(64) NOT NULL,
  ROLE_ID VARCHAR(64) NOT NULL,
  PRIMARY KEY (USER_ID, ROLE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS FM_LEVEL (
  NID VARCHAR(64) NOT NULL,
  NAME VARCHAR(128) NOT NULL,
  DESCRIPTION VARCHAR(500) NULL,
  `LEVEL` INT NOT NULL,
  PRIMARY KEY (NID),
  UNIQUE KEY UK_FM_LEVEL_NO (`LEVEL`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS FM_NODE (
  NID VARCHAR(64) NOT NULL,
  NAME VARCHAR(200) NOT NULL,
  DESCRIPTION VARCHAR(500) NULL,
  LEVEL_NID VARCHAR(64) NOT NULL,
  PNID VARCHAR(64) NULL,
  SORT_NO INT NOT NULL DEFAULT 0,
  IS_DELETED TINYINT NOT NULL DEFAULT 0,
  CREATE_ON DATETIME NOT NULL,
  LAST_UPDATE_ON DATETIME NOT NULL,
  PRIMARY KEY (NID),
  KEY IX_FM_NODE_PNID (PNID),
  KEY IX_FM_NODE_LEVEL (LEVEL_NID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE OR REPLACE VIEW V_FACTORY_MODEL AS
SELECT
  n.NID AS NID,
  n.NAME AS NAME,
  n.DESCRIPTION AS DESCRIPTION,
  n.LEVEL_NID AS LEVEL_NID,
  n.CREATE_ON AS CREATE_ON,
  n.LAST_UPDATE_ON AS LAST_UPDATE_ON,
  l.`LEVEL` AS `LEVEL`,
  p.NID AS PNID,
  p.NAME AS PNAME,
  p.LEVEL_NID AS PLEVEL_NID
FROM FM_NODE n
INNER JOIN FM_LEVEL l ON l.NID = n.LEVEL_NID
LEFT JOIN FM_NODE p ON p.NID = n.PNID AND p.IS_DELETED = 0
WHERE n.IS_DELETED = 0;
