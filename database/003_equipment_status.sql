-- 设备状态报文。表名沿用滁州，方便对照。齐套检查、维修工单和停机按天拆分这一版不做。

CREATE TABLE IF NOT EXISTS EAM_DEV (
  NID VARCHAR(64) NOT NULL,
  DEV_CODE VARCHAR(64) NULL,
  DEV_STATUS VARCHAR(32) NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  PRIMARY KEY (NID),
  KEY IX_EAM_DEV_CODE (DEV_CODE, DELETE_FLAG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS EAM_EC_EQUIP_STATUS (
  NID VARCHAR(64) NOT NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  CREATE_TIME DATETIME NULL,
  EQUIPMENT_CODE VARCHAR(64) NULL,
  EMPLOYEE_NO VARCHAR(64) NULL,
  EQUIPMENT_MODEL VARCHAR(32) NULL,
  EQUIPMENT_STATUS_ID VARCHAR(64) NULL,
  REASON_CODE VARCHAR(128) NULL,
  DESCRIPTION VARCHAR(500) NULL,
  MODIFY_TIME DATETIME NULL,
  PRIMARY KEY (NID),
  KEY IX_EAM_EC_EQUIP_STATUS_CODE (EQUIPMENT_CODE, CREATE_TIME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS EAM_OEE_DOWNTIME_REACORD (
  ID VARCHAR(64) NOT NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  CREATE_TIME DATETIME NULL,
  DEV_CODE VARCHAR(64) NULL,
  START_TIME DATETIME NULL,
  END_TIME DATETIME NULL,
  STATUS INT NOT NULL DEFAULT 0,
  CREATE_BY VARCHAR(64) NULL,
  FIELD1 VARCHAR(128) NULL,
  LEVEL1_LOSS_CODE VARCHAR(128) NULL,
  LEVEL2_LOSS_CODE VARCHAR(128) NULL,
  LEVEL3_LOSS_CODE VARCHAR(128) NULL,
  LEVEL4_LOSS_CODE VARCHAR(128) NULL,
  PRIMARY KEY (ID),
  KEY IX_EAM_OEE_DOWNTIME_CODE (DEV_CODE, DELETE_FLAG, CREATE_TIME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS EAM_FAULT_RECORD (
  ID VARCHAR(64) NOT NULL,
  CREATE_BY VARCHAR(64) NULL,
  CREATE_TIME DATETIME NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  STATUS INT NOT NULL DEFAULT 0,
  START_TIME DATETIME NULL,
  END_TIME DATETIME NULL,
  DEV_CODE VARCHAR(64) NULL,
  FAULT_CODE VARCHAR(64) NULL,
  FAULT_DESC VARCHAR(500) NULL,
  FAULT_LEVEL VARCHAR(64) NULL,
  MODIFY_TIME DATETIME NULL,
  MODIFY_BY VARCHAR(64) NULL,
  PRIMARY KEY (ID),
  KEY IX_EAM_FAULT_RECORD_CODE (DEV_CODE, FAULT_CODE, DELETE_FLAG, STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PRD_EQP_PARA_HIS (
  NID VARCHAR(64) NOT NULL,
  CREATE_BY VARCHAR(64) NULL,
  CREATE_TIME DATETIME NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  EQUIPMENT_CODE VARCHAR(64) NULL,
  STEP_ID VARCHAR(64) NULL,
  ORDER_NO VARCHAR(64) NULL,
  MATERIAL_CODE VARCHAR(64) NULL,
  OPERATION_CODE VARCHAR(64) NULL,
  PARAM_CODE VARCHAR(64) NULL,
  PARAM_NAME VARCHAR(200) NULL,
  COLLECTED_VALUE VARCHAR(200) NULL,
  TARGET_VALUE VARCHAR(200) NULL,
  PRIMARY KEY (NID),
  KEY IX_PRD_EQP_PARA_HIS_CODE (EQUIPMENT_CODE, CREATE_TIME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
