-- 上下料回执、物料校验、零部件寿命。齐套、维修工单、停机按天拆分不在这里。
-- 在制上料、下料、零部件装拆不在这里调用，回执只改队列和执行参数。

CREATE TABLE IF NOT EXISTS MM_MATERIAL_STOCK_DETAIL (
  NID VARCHAR(64) NOT NULL,
  MATERIAL_BATCH VARCHAR(128) NULL,
  MATERIAL_CODE VARCHAR(128) NULL,
  REMAIN_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
  FEED_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
  LOAD_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  MODIFY_BY VARCHAR(64) NULL,
  MODIFY_TIME DATETIME NULL,
  PRIMARY KEY (NID),
  KEY IX_MM_STOCK_BATCH (MATERIAL_BATCH)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PRD_RESOURCE_CONTENT (
  NID VARCHAR(64) NOT NULL,
  EQUIPMENT_CODE VARCHAR(64) NULL,
  ORDER_NO VARCHAR(128) NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  PRIMARY KEY (NID),
  KEY IX_PRD_RESOURCE_CONTENT_EQ (EQUIPMENT_CODE, DELETE_FLAG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS POM_ORDER_BOM (
  NID VARCHAR(64) NOT NULL,
  ORDER_NO VARCHAR(128) NULL,
  MATERIAL_CODE VARCHAR(128) NULL,
  OPERATION_CODE VARCHAR(64) NULL,
  BOM_UOM VARCHAR(64) NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  PRIMARY KEY (NID),
  KEY IX_POM_ORDER_BOM_ORDER (ORDER_NO, DELETE_FLAG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PRD_RESOURCE_LOADING (
  NID VARCHAR(64) NOT NULL,
  EQUIPMENT_CODE VARCHAR(64) NULL,
  MATERIAL_CODE VARCHAR(128) NULL,
  MATERIAL_SEQ_NO BIGINT NOT NULL DEFAULT 0,
  ORDER_NO VARCHAR(128) NULL,
  QUANTITY DECIMAL(18,4) NOT NULL DEFAULT 0,
  TOTAL_QUANTITY DECIMAL(18,4) NOT NULL DEFAULT 0,
  MATERIAL_BATCH VARCHAR(128) NULL,
  FEED_LOCATION VARCHAR(128) NULL,
  CONSUMED_QTY DECIMAL(18,4) NOT NULL DEFAULT 0,
  UOM VARCHAR(64) NULL,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  ARCHIVE_FLAG INT NOT NULL DEFAULT 0,
  CREATE_BY VARCHAR(64) NULL,
  CREATE_TIME DATETIME NULL,
  PRIMARY KEY (NID),
  KEY IX_PRD_RESOURCE_LOADING_EQ (EQUIPMENT_CODE, CREATE_TIME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS PRD_RESOURCE_LOADING_HIS (
  NID VARCHAR(64) NOT NULL,
