-- 设备心跳。表名沿用滁州队列，方便对照报文。领走后 OPERATION_ID 保持本次凭证，不设回空闲号。

CREATE TABLE IF NOT EXISTS EQUIPMENT_DI_FLAGS (
  NID VARCHAR(64) NOT NULL,
  EQUIPMENT_CODE VARCHAR(64) NULL,
  EQUIPMENT_CONTROL INT NOT NULL DEFAULT 0,
  MATERIAL_LOAD INT NOT NULL DEFAULT 0,
  MATERIAL_UNLOAD INT NOT NULL DEFAULT 0,
  PART_LAOD INT NOT NULL DEFAULT 0,
  PART_UNLAOD INT NOT NULL DEFAULT 0,
  GET_PARA_FLAG INT NOT NULL DEFAULT 0,
  GET_BATCH_FLAG INT NOT NULL DEFAULT 0,
  GET_RECIPE_FLAG INT NOT NULL DEFAULT 0,
  GET_REASON_FLAG INT NOT NULL DEFAULT 0,
  DEL_BATCH_FLAG INT NOT NULL DEFAULT 0,
  SEND_ORDER INT NOT NULL DEFAULT 0,
  DEL_ORDER INT NOT NULL DEFAULT 0,
  GET_BATTERY_CAPACITY_RULE_FLAG INT NOT NULL DEFAULT 0,
  GET_CAPACITY_PARA_FLAG INT NOT NULL DEFAULT 0,
  SEND_EQUIPMENT_CHANNEL_FLAG INT NOT NULL DEFAULT 0,
  OPERATION_ID VARCHAR(64) NULL,
  OPERATION_STATUS INT NOT NULL DEFAULT 0,
  DELETE_FLAG INT NOT NULL DEFAULT 0,
  MODIFY_TIME DATETIME NULL,
  OPERATION_TIME DATETIME NULL,
  PRIMARY KEY (NID),
  KEY IX_EQUIPMENT_DI_FLAGS_CODE (EQUIPMENT_CODE, DELETE_FLAG, OPERATION_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

